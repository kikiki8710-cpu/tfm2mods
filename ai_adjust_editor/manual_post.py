# 배포용 설명서 최종 손질 — 완성된 본문에 대고 한 번에 적용한다.
#  (생성기 안에서 정규식을 겹겹이 쌓으면 이스케이프가 꼬여 되레 놓치는 게 생겨서 분리했다.)
import re

RULES = [
    # ── 개발 이력·내부 판정 표현 ──
    (r'⚠?\[정정[^\]]*\]\s*', ''),
    (r'\(구 [^)]{0,40}오기\)', ''),
    (r'\(구 문서[^)]*\)', ''),
    (r'구 .{0,14}표기는[^.]*\.', ''),
    (r'✅\s*\[재배선\]\s*', ''),
    (r'\[재배선\]\s*', ''),
    (r'★?재배선(?:됨| 완료)?\s*', ''),
    (r'△\s*부분반영\s*[—-]\s*', ''),
    (r'★커버블록이 막혀 있어 값이 안 먹었음\.?', ''),
    (r'구 문서', '이전 기록'),
    # ── 내부 용어 잔재 ──
    (r'\bsubplan\s*(\d+)', r'실행 단위 \1'),
    (r'\bsubplan\b', '실행 단위'),
    (r'\bdisc\s*(\d+)', r'판단 \1'),
    (r'\bparam\s*(\d)', r'항목 \1'),
    (r'\bimm32[^)]*', '내부 표현 한계로 아주 큰 값은 넣을 수 없습니다'),
    (r'\bimm\b', '값'),
    (r'\bRVA\b', '위치'),
    (r'바이트\s*패치|byte-patch', '값 교체'),
    (r'(\d+)\s*사이트', r'\1곳'),
    (r'사이트', '자리'),
    (r'레버리지', '영향 범위'),
    (r'레버(?!는)', '조절값'),
    (r'위협 평가 정본', '위협 평가 본체'),
    (r'평가 정본', '평가 본체'),
    (r'정본 함수 전용', '본체 전용'),
    (r'정본', '본체'),
    (r'branch\s*[ABC]', '경로'),
    (r'사본\s*\[[ABC]\]', '사본'),
    # ── 표시 정리 ──
    (r'\(\s*코드\s*0x[0-9a-fA-F]+\s*\)', ''),
    (r'\(0x[0-9a-fA-F]+\s*=\s*(\d+)\)', r'(\1)'),
    (r'원본\s*0x[0-9a-fA-F]+\s*=\s*', '원본 '),
    (r'원본\s*0x[0-9a-fA-F]+', '원본'),
    (r'0x[0-9a-fA-F]{4,}', ''),
    (r'✅', ''),
    (r'[ \t]{2,}', ' '),
    (r'[ \t]+\.', '.'),
    (r'\(\s*\)', ''),
    # 적용 결과 로그를 가리키는 내부 표기
    (r'\(?\s*applied\s*=\s*[^)\n]*\)?', ''),
    (r'⚠?정정\s*[:：]\s*', ''),
    (r'적용확인 로그\s*applied\s*카운트로\s*', '적용 결과 기록으로 '),
    (r'적용확인 로그', '적용 결과 기록'),
]

def fix(text: str) -> str:
    # ⚠``` 코드 블록 안은 건드리지 않는다 — 공백 압축 규칙이 그림의 정렬을 뭉갠다(실제로 그랬다).
    parts = text.split("```")
    for i in range(0, len(parts), 2):        # 짝수 인덱스 = 펜스 바깥
        for pat, rep in RULES:
            parts[i] = re.sub(pat, rep, parts[i])
    text = "```".join(parts)
    # ⚠표 칸 공백 정리는 **줄 단위로만** 한다.
    #   `\s`에 줄바꿈이 포함돼 전역으로 돌리면 표 앞의 문장과 표가 한 줄로 뭉개진다(실제로 그랬다).
    out = []
    for ln in text.split("\n"):
        if ln.lstrip().startswith("|"):
            ln = re.sub(r'\|[ \t]+', '| ', ln)
            ln = re.sub(r'[ \t]+\|', ' |', ln)
        out.append(ln.rstrip())
    return "\n".join(out)
